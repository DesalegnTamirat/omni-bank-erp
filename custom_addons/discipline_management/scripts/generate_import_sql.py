#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Generate a standalone SQL script to import all Bunna Bank discipline data
into any Odoo 19 PostgreSQL database directly (no Odoo shell needed).

Usage:
    python generate_import_sql.py > import_discipline_data.sql

Then on the production DB:
    psql -U odoo -d ERP_TEST3 -f import_discipline_data.sql
"""

import xml.etree.ElementTree as ET
import re
import os

XML_FILE = os.path.join(os.path.dirname(__file__), '../data/bunna_regulation_seed_data.xml')


def sql_str(val):
    if val is None:
        return 'NULL'
    return "E'" + str(val).replace("'", "''").replace('\\', '\\\\') + "'"


def parse_xml():
    tree = ET.parse(XML_FILE)
    root = tree.getroot()
    data = root.find('data')

    policies = {}
    categories = {}
    articles = {}
    offenses = []

    for record in data.findall('record'):
        rid = record.get('id')
        model = record.get('model')
        fields = {f.get('name'): f for f in record.findall('field')}

        def fval(name):
            f = fields.get(name)
            if f is None:
                return None
            if f.get('ref'):
                return ('ref', f.get('ref'))
            return f.text or ''

        if model == 'discipline.policy.version':
            policies[rid] = {
                'name': fval('name'),
                'version_number': fval('version_number'),
                'staff_category': fval('staff_category'),
                'chapter_reference': fval('chapter_reference'),
                'effective_date': fval('effective_date'),
                'state': fval('state'),
                'description': fval('description'),
            }

        elif model == 'discipline.offense.category':
            categories[rid] = {
                'name': fval('name'),
                'code': fval('code'),
                'description': fval('description'),
                'active': fval('active'),
            }

        elif model == 'discipline.article':
            articles[rid] = {
                'article_number': fval('article_number'),
                'name': fval('name'),
                'policy_version_id': fval('policy_version_id'),
                'staff_category': fval('staff_category'),
                'severity_level_id': fval('severity_level_id'),
                'statutory_text': fval('statutory_text'),
                'description': fval('description'),
                'active': fval('active'),
            }

        elif model == 'discipline.offense':
            o = {
                'rid': rid,
                'name': fval('name'),
                'title': fval('title'),
                'has_distinct_title': fval('has_distinct_title'),
                'sub_article_code': fval('sub_article_code'),
                'full_clause_text': fval('full_clause_text'),
                'description': fval('description'),
                'article_id': fval('article_id'),
                'category_id': fval('category_id'),
                'severity_level_id': fval('severity_level_id'),
                'punishment_type': fval('punishment_type'),
                'penalty_percentage': fval('penalty_percentage'),
                'fine_days': fval('fine_days'),
                'staff_category': fval('staff_category'),
                'active': fval('active'),
                'sequence': fval('sequence'),
            }
            offenses.append(o)

    return policies, categories, articles, offenses


def generate_sql():
    policies, categories, articles, offenses = parse_xml()

    lines = []
    lines.append("-- ============================================================")
    lines.append("-- Bunna Bank Discipline Data Import Script")
    lines.append("-- Generated by generate_import_sql.py")
    lines.append("-- Safe to run multiple times (uses ON CONFLICT DO NOTHING / UPDATE)")
    lines.append("-- ============================================================")
    lines.append("")
    lines.append("BEGIN;")
    lines.append("")

    # ── 1. Policy Versions ──────────────────────────────────────────────────
    lines.append("-- --------------------------------------------------------")
    lines.append("-- 1. Policy Versions")
    lines.append("-- --------------------------------------------------------")
    for rid, p in policies.items():
        lines.append(f"""
INSERT INTO discipline_policy_version (name, version_number, staff_category, chapter_reference, effective_date, state, description, active)
VALUES (
    {sql_str(p['name'])},
    {sql_str(p['version_number'])},
    {sql_str(p['staff_category'])},
    {sql_str(p['chapter_reference'])},
    {sql_str(p['effective_date']) if p['effective_date'] else 'NULL'},
    {sql_str(p['state'] or 'active')},
    {sql_str(p['description'])},
    TRUE
)
ON CONFLICT (version_number) DO UPDATE SET
    name = EXCLUDED.name,
    staff_category = EXCLUDED.staff_category,
    state = EXCLUDED.state;
-- store mapping: {rid} -> version_number={p['version_number']}""")

    lines.append("")

    # ── 2. Offense Categories ───────────────────────────────────────────────
    lines.append("-- --------------------------------------------------------")
    lines.append("-- 2. Offense Categories")
    lines.append("-- --------------------------------------------------------")
    for rid, c in categories.items():
        active_val = 'TRUE' if str(c['active']).lower() in ('true', '1', 'yes', '') else 'FALSE'
        lines.append(f"""
INSERT INTO discipline_offense_category (name, code, description, active)
VALUES (
    {sql_str(c['name'])},
    {sql_str(c['code'])},
    {sql_str(c['description'])},
    {active_val}
)
ON CONFLICT (code) DO UPDATE SET
    name = EXCLUDED.name,
    description = EXCLUDED.description,
    active = EXCLUDED.active;""")

    lines.append("")

    # ── 3. Articles ─────────────────────────────────────────────────────────
    lines.append("-- --------------------------------------------------------")
    lines.append("-- 3. Regulatory Articles")
    lines.append("-- --------------------------------------------------------")
    for rid, a in articles.items():
        policy_ref = a['policy_version_id']
        policy_lookup = ""
        if isinstance(policy_ref, tuple) and policy_ref[0] == 'ref':
            prid = policy_ref[1]
            p = policies.get(prid, {})
            vnum = p.get('version_number', '')
            policy_lookup = f"(SELECT id FROM discipline_policy_version WHERE version_number = {sql_str(vnum)} LIMIT 1)"
        else:
            policy_lookup = 'NULL'

        sev_ref = a['severity_level_id']
        if isinstance(sev_ref, tuple) and sev_ref[0] == 'ref':
            sev_code_map = {
                'severity_level_1': '1',
                'severity_level_2': '2',
                'severity_level_3': '3',
                'severity_level_4': '4',
                'severity_level_5': '5',
            }
            sev_code = sev_code_map.get(sev_ref[1], None)
            if sev_code:
                sev_lookup = f"(SELECT id FROM discipline_severity_level WHERE code = {sql_str(sev_code)} LIMIT 1)"
            else:
                sev_lookup = 'NULL'
        else:
            sev_lookup = 'NULL'

        art_num = a['article_number']
        active_val = 'TRUE'
        lines.append(f"""
INSERT INTO discipline_article (article_number, name, policy_version_id, staff_category, severity_level_id, statutory_text, description, active)
VALUES (
    {sql_str(art_num)},
    {sql_str(a['name'])},
    {policy_lookup},
    {sql_str(a['staff_category'])},
    {sev_lookup},
    {sql_str(a['statutory_text'])},
    {sql_str(a['description'])},
    {active_val}
)
ON CONFLICT (article_number) DO UPDATE SET
    name = EXCLUDED.name,
    policy_version_id = COALESCE(EXCLUDED.policy_version_id, discipline_article.policy_version_id),
    active = EXCLUDED.active;""")

    lines.append("")

    # ── 4. Offenses ─────────────────────────────────────────────────────────
    lines.append("-- --------------------------------------------------------")
    lines.append("-- 4. Offense Classifications (184 statutory offenses)")
    lines.append("-- --------------------------------------------------------")
    lines.append("-- NOTE: Uses sub_article_code as the unique key to avoid duplicates.")
    lines.append("")

    # Map article ref -> article_number
    art_ref_to_num = {}
    for art_rid, a in articles.items():
        art_ref_to_num[art_rid] = a['article_number']

    # Map category ref -> code
    cat_ref_to_code = {}
    for cat_rid, c in categories.items():
        cat_ref_to_code[cat_rid] = c['code']

    sev_code_map = {
        'severity_level_1': '1',
        'severity_level_2': '2',
        'severity_level_3': '3',
        'severity_level_4': '4',
        'severity_level_5': '5',
    }

    for o in offenses:
        sub_code = o['sub_article_code']
        if not sub_code:
            sub_code = o['rid']

        # article lookup
        art_ref = o['article_id']
        if isinstance(art_ref, tuple) and art_ref[0] == 'ref':
            art_num = art_ref_to_num.get(art_ref[1], '')
            art_lookup = f"(SELECT id FROM discipline_article WHERE article_number = {sql_str(art_num)} LIMIT 1)"
        else:
            art_lookup = 'NULL'

        # category lookup
        cat_ref = o['category_id']
        if isinstance(cat_ref, tuple) and cat_ref[0] == 'ref':
            cat_code = cat_ref_to_code.get(cat_ref[1], '')
            cat_lookup = f"(SELECT id FROM discipline_offense_category WHERE code = {sql_str(cat_code)} LIMIT 1)"
        else:
            cat_lookup = 'NULL'

        # severity lookup
        sev_ref = o['severity_level_id']
        if isinstance(sev_ref, tuple) and sev_ref[0] == 'ref':
            sev_code = sev_code_map.get(sev_ref[1], None)
            sev_lookup = f"(SELECT id FROM discipline_severity_level WHERE code = {sql_str(sev_code)} LIMIT 1)" if sev_code else 'NULL'
        else:
            sev_lookup = 'NULL'

        pct = o['penalty_percentage'] or '0'
        days = o['fine_days'] or '0'
        seq = o['sequence'] or '10'
        active_val = 'TRUE' if str(o['active'] or 'True').lower() in ('true', '1', 'yes', '') else 'FALSE'
        distinct_title = 'TRUE' if str(o['has_distinct_title'] or 'False').lower() in ('true', '1', 'yes') else 'FALSE'
        staff_cat = o['staff_category'] or 'non_managerial'
        punishment = o['punishment_type'] or 'dismissal'

        lines.append(f"""INSERT INTO discipline_offense (
    name, title, has_distinct_title, sub_article_code, full_clause_text, description,
    article_id, category_id, severity_level_id,
    punishment_type, penalty_percentage, fine_days,
    staff_category, active, sequence,
    message_last_post
)
SELECT
    {sql_str(o['name'])},
    {sql_str(o['title'])},
    {distinct_title},
    {sql_str(sub_code)},
    {sql_str(o['full_clause_text'])},
    {sql_str(o['description'])},
    {art_lookup},
    {cat_lookup},
    {sev_lookup},
    {sql_str(punishment)},
    {pct},
    {days},
    {sql_str(staff_cat)},
    {active_val},
    {seq},
    NOW()
WHERE NOT EXISTS (
    SELECT 1 FROM discipline_offense WHERE sub_article_code = {sql_str(sub_code)}
);""")

    lines.append("")
    lines.append("-- --------------------------------------------------------")
    lines.append("-- 5. Recompute stored computed fields")
    lines.append("-- --------------------------------------------------------")
    lines.append("""
-- Update article_number (stored related field) from linked article
UPDATE discipline_offense o
SET article_number = a.article_number
FROM discipline_article a
WHERE o.article_id = a.id
  AND (o.article_number IS NULL OR o.article_number != a.article_number);

-- Update policy_version_id (stored related field) from linked article
UPDATE discipline_offense o
SET policy_version_id = a.policy_version_id
FROM discipline_article a
WHERE o.article_id = a.id
  AND (o.policy_version_id IS NULL OR o.policy_version_id != a.policy_version_id);
""")

    lines.append("COMMIT;")
    lines.append("")
    lines.append("-- --------------------------------------------------------")
    lines.append("-- Verification Queries (run after import)")
    lines.append("-- --------------------------------------------------------")
    lines.append("""
SELECT 'Policy Versions' AS table_name, COUNT(*) AS count FROM discipline_policy_version
UNION ALL
SELECT 'Offense Categories', COUNT(*) FROM discipline_offense_category
UNION ALL
SELECT 'Articles', COUNT(*) FROM discipline_article
UNION ALL
SELECT 'Offenses (total)', COUNT(*) FROM discipline_offense
UNION ALL
SELECT 'Offenses with article', COUNT(*) FROM discipline_offense WHERE article_id IS NOT NULL
UNION ALL
SELECT 'Offenses with category', COUNT(*) FROM discipline_offense WHERE category_id IS NOT NULL;
""")

    return '\n'.join(lines)


if __name__ == '__main__':
    sql = generate_sql()
    out_path = os.path.join(os.path.dirname(__file__), 'import_discipline_data.sql')
    with open(out_path, 'w', encoding='utf-8') as f:
        f.write(sql)
    print(f"SQL written to: {out_path}")
    print(f"Lines: {len(sql.splitlines())}")
