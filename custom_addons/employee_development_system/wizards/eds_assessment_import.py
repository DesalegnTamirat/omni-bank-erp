# -*- coding: utf-8 -*-
"""Round-trip CSV entry for session pre/post questions and participant answers."""

import base64
import binascii
import csv
import io
import math
import re
from collections import defaultdict

from odoo import fields, models, _
from odoo.exceptions import ValidationError


CSV_COLUMNS = (
    'session_id', 'session_ref', 'assessment_type',
    'employee_id', 'employee_badge', 'employee_name',
    'question_id', 'question', 'max_points',
    'answer', 'awarded_points', 'comments', 'assessment_notes',
)


_SPREADSHEET_FORMULA = re.compile(r"^'*\s*[=+\-@]")


def _spreadsheet_safe_text(value):
    """Keep untrusted text from executing as a formula when CSV is opened."""
    value = str(value or '')
    return "'" + value if _SPREADSHEET_FORMULA.match(value) else value


def _restore_spreadsheet_text(value):
    """Undo only the escape generated by the exported template."""
    return value[1:] if value.startswith("'") and _SPREADSHEET_FORMULA.match(value[1:]) else value


class EdsAssessmentImport(models.TransientModel):
    _name = 'eds.assessment.import'
    _description = 'Pre/Post Assessment Answer Import and Export'

    session_id = fields.Many2one('eds.session', string='Session', required=True)
    assessment_type = fields.Selection(
        [('pre', 'Pre-Assessment'), ('post', 'Post-Assessment')],
        string='Assessment Type', required=True, default='pre')
    csv_file = fields.Binary(string='Completed Assessment CSV', attachment=False)
    filename = fields.Char(string='Uploaded File Name')
    template_file = fields.Binary(string='CSV Template', readonly=True, attachment=False)
    template_filename = fields.Char(string='Template File Name', readonly=True)
    overwrite_employee_answers = fields.Boolean(
        string='Allow correcting employee-submitted answers',
        help='If selected, imported answer text may replace a different answer '
             'already submitted by an employee. Grading an unchanged answer '
             'does not require this option.')
    replace_legacy_score = fields.Boolean(
        string='Replace an existing score-only result',
        help='An imported set of question answers and grades can replace an '
             'older score that had no recorded answers only if selected.')
    result_log = fields.Text(string='Import Summary', readonly=True)

    def _questions(self):
        self.ensure_one()
        Question = self.env['eds.assessment.question']
        domain = [
            ('session_id', '=', self.session_id.id),
            ('assessment_type', '=', self.assessment_type),
        ]
        questions = Question.search(domain, order='sequence, id')
        if not questions:
            Question.seed_from_instrument(self.session_id, self.assessment_type)
            questions = Question.search(domain, order='sequence, id')
        if not questions:
            raise ValidationError(_(
                'Add pre/post assessment questions to this session (or publish '
                'a Level 2 instrument for its course) before exporting or '
                'importing answers.'))
        return questions

    def _participants(self):
        self.ensure_one()
        participants = self.session_id._accepted_attendance_enrollments().filtered(
            lambda enrollment: enrollment.state in ('enrolled', 'completed')
        ).mapped('employee_id')
        if not participants:
            raise ValidationError(_(
                'The session has no enrolled or completed participants.'))
        return participants.sorted(lambda employee: (employee.name or '', employee.id))

    def action_download_template(self):
        """Export one row per participant/question, including saved answers."""
        self.ensure_one()
        participants = self._participants()
        questions = self._questions()
        assessments = self.env['eds.assessment'].search([
            ('session_id', '=', self.session_id.id),
            ('assessment_type', '=', self.assessment_type),
            ('employee_id', 'in', participants.ids),
        ])
        by_employee = {row.employee_id.id: row for row in assessments}
        output = io.StringIO(newline='')
        writer = csv.DictWriter(output, fieldnames=CSV_COLUMNS)
        writer.writeheader()
        for employee in participants:
            assessment = by_employee.get(employee.id)
            by_question = {
                line.question_id.id: line
                for line in assessment.answer_ids
            } if assessment else {}
            for question in questions:
                answer = by_question.get(question.id)
                writer.writerow({
                    'session_id': self.session_id.id,
                    'session_ref': _spreadsheet_safe_text(self.session_id.name),
                    'assessment_type': self.assessment_type,
                    'employee_id': employee.id,
                    'employee_badge': _spreadsheet_safe_text(
                        employee.identification_id or employee.barcode),
                    'employee_name': _spreadsheet_safe_text(employee.name),
                    'question_id': question.id,
                    'question': _spreadsheet_safe_text(question.question_text),
                    'max_points': question.max_points,
                    'answer': _spreadsheet_safe_text(
                        answer.answer_text if answer else ''),
                    'awarded_points': answer.awarded_points if answer and answer.is_graded else '',
                    'comments': _spreadsheet_safe_text(
                        answer.comments if answer else ''),
                    'assessment_notes': _spreadsheet_safe_text(
                        assessment.notes if assessment else ''),
                })
        self.write({
            'template_file': base64.b64encode(output.getvalue().encode('utf-8-sig')),
            'template_filename': 'eds_%s_%s_assessment.csv' % (
                self.session_id.id, self.assessment_type),
        })
        return {
            'type': 'ir.actions.act_url',
            'url': '/web/content/?model=eds.assessment.import&id=%s&field=template_file'
                   '&filename_field=template_filename&download=true' % self.id,
            'target': 'self',
        }

    @staticmethod
    def _positive_id(raw_value, label, line_number):
        try:
            value = int(raw_value)
        except (TypeError, ValueError):
            raise ValidationError(_(
                'Row %(row)d: %(label)s must be a positive database ID.') % {
                    'row': line_number, 'label': label})
        if value <= 0:
            raise ValidationError(_(
                'Row %(row)d: %(label)s must be a positive database ID.') % {
                    'row': line_number, 'label': label})
        return value

    def _read_rows(self):
        self.ensure_one()
        if not self.csv_file:
            raise ValidationError(_('Choose a completed assessment CSV file.'))
        try:
            content = base64.b64decode(self.csv_file, validate=True).decode('utf-8-sig')
        except (ValueError, UnicodeError, binascii.Error) as error:
            raise ValidationError(_('Read the CSV as UTF-8: %s') % error) from error
        reader = csv.DictReader(io.StringIO(content, newline=''))
        if not reader.fieldnames or len(reader.fieldnames) != len(set(reader.fieldnames)):
            raise ValidationError(_('The CSV header is missing or has duplicate columns.'))
        required = {'employee_id', 'question_id', 'answer', 'awarded_points'}
        if not required.issubset(reader.fieldnames):
            raise ValidationError(_('The CSV must contain these columns: %s') %
                                  ', '.join(sorted(required)))
        rows = []
        for line_number, row in enumerate(reader, start=2):
            if None in row:
                raise ValidationError(_(
                    'Row %d has more cells than the CSV header.') % line_number)
            if not any(str(value or '').strip() for value in row.values()):
                continue
            rows.append((line_number, {
                key: _restore_spreadsheet_text(str(value or ''))
                for key, value in row.items()
            }))
        if not rows:
            raise ValidationError(_('The CSV has no participant answers.'))
        return rows

    def _validated_groups(self, rows, questions, participants):
        """Validate the entire upload before changing any assessment record."""
        question_by_id = {question.id: question for question in questions}
        employee_by_id = {employee.id: employee for employee in participants}
        expected = set(question_by_id)
        grouped = defaultdict(dict)
        notes = defaultdict(set)
        errors = []
        for line_number, row in rows:
            try:
                if row.get('session_id') and self._positive_id(
                        row['session_id'], 'session_id', line_number) != self.session_id.id:
                    raise ValidationError(_('The row belongs to another session.'))
                if row.get('session_ref') and row['session_ref'] != self.session_id.name:
                    raise ValidationError(_('The session reference does not match.'))
                if row.get('assessment_type') and row['assessment_type'] != self.assessment_type:
                    raise ValidationError(_('The assessment type does not match.'))
                employee_id = self._positive_id(
                    row.get('employee_id'), 'employee_id', line_number)
                question_id = self._positive_id(
                    row.get('question_id'), 'question_id', line_number)
                employee = employee_by_id.get(employee_id)
                question = question_by_id.get(question_id)
                if not employee:
                    raise ValidationError(_('The participant is not enrolled in this session.'))
                if not question:
                    raise ValidationError(_('The question does not belong to this session and type.'))
                if row.get('employee_badge') and row['employee_badge'] not in (
                        employee.identification_id, employee.barcode):
                    raise ValidationError(_('The employee badge does not match the participant ID.'))
                if row.get('question') and row['question'] != question.question_text:
                    raise ValidationError(_('The question text changed. Download a new template.'))
                if row.get('max_points'):
                    try:
                        exported_max = float(row['max_points'])
                    except ValueError as error:
                        raise ValidationError(_('max_points must be a number.')) from error
                    if not math.isclose(exported_max, question.max_points,
                                        rel_tol=0, abs_tol=0.000001):
                        raise ValidationError(_(
                            'The question maximum changed. Download a new template.'))
                if question_id in grouped[employee_id]:
                    raise ValidationError(_('The same participant/question occurs twice.'))
                answer_text = row.get('answer', '')
                if not answer_text.strip():
                    raise ValidationError(_('Every question needs an answer.'))
                raw_points = row.get('awarded_points', '').strip()
                points = 0.0
                if raw_points:
                    try:
                        points = float(raw_points)
                    except ValueError as error:
                        raise ValidationError(_('Awarded points must be a number.')) from error
                    if not math.isfinite(points) or points < 0 or points > question.max_points:
                        raise ValidationError(_(
                            'Awarded points must be between 0 and %s.') % question.max_points)
                grouped[employee_id][question_id] = {
                    'answer_text': answer_text,
                    'awarded_points': points,
                    'is_graded': bool(raw_points),
                    'comments': row.get('comments', ''),
                    'line_number': line_number,
                }
                if row.get('assessment_notes'):
                    notes[employee_id].add(row['assessment_notes'])
            except ValidationError as error:
                errors.append(_('Row %(row)d: %(error)s') % {
                    'row': line_number, 'error': error.args[0]})
        for employee_id, answers in grouped.items():
            missing = expected - set(answers)
            if missing:
                errors.append(_(
                    'Participant %(employee)s: the CSV is missing %(count)d question row(s).') % {
                        'employee': employee_by_id[employee_id].name,
                        'count': len(missing)})
            if len(notes[employee_id]) > 1:
                errors.append(_(
                    'Participant %s: assessment_notes differs between rows.') %
                    employee_by_id[employee_id].name)
        if errors:
            raise ValidationError(_('Nothing was imported. Correct the CSV:\n%s') %
                                  '\n'.join(errors[:30]))
        return grouped, notes

    def action_import_assessments(self):
        self.ensure_one()
        participants = self._participants()
        questions = self._questions()
        grouped, notes = self._validated_groups(
            self._read_rows(), questions, participants)
        Assessment = self.env['eds.assessment']
        Answer = self.env['eds.assessment.answer']
        existing = Assessment.search([
            ('session_id', '=', self.session_id.id),
            ('assessment_type', '=', self.assessment_type),
            ('employee_id', 'in', list(grouped)),
        ])
        existing_by_employee = {item.employee_id.id: item for item in existing}
        # Finish conflict checking before any writes. An employee answer is never
        # silently replaced by an edited spreadsheet cell.
        for employee_id, answer_rows in grouped.items():
            assessment = existing_by_employee.get(employee_id)
            if not assessment:
                continue
            if (assessment.entry_method == 'score_only'
                    and (assessment.score or assessment.state == 'graded')
                    and not self.replace_legacy_score):
                raise ValidationError(_(
                    'Nothing was imported. Participant %s already has a '
                    'score-only result. Select "Replace an existing score-only '
                    'result" only if the itemized result is intended to replace it.'
                ) % assessment.employee_id.name)
            existing_answers = {
                line.question_id.id: line for line in assessment.answer_ids
            }
            for question_id, vals in answer_rows.items():
                old = existing_answers.get(question_id)
                if (assessment.entry_method == 'employee'
                        and old and (old.answer_text or '').strip()
                        and (old.answer_text or '') != vals['answer_text']
                        and not self.overwrite_employee_answers):
                    raise ValidationError(_(
                        'Nothing was imported. Participant %(employee)s, row '
                        '%(row)d changes an employee assessment answer. Select '
                        '"Allow correcting employee-submitted answers" only '
                        'if that change is intentional.') % {
                            'employee': assessment.employee_id.name,
                            'row': vals['line_number'],
                        })
                if assessment.state == 'graded' and not vals['is_graded']:
                    raise ValidationError(_(
                        'Nothing was imported. Participant %(employee)s has a '
                        'graded assessment; every awarded_points cell must '
                        'remain filled when updating it.') % {
                            'employee': assessment.employee_id.name})
        created_count = updated_count = graded_count = pending_count = 0
        for employee_id, answer_rows in grouped.items():
            assessment = existing_by_employee.get(employee_id)
            if assessment:
                updated_count += 1
                if assessment.entry_method == 'score_only' and self.replace_legacy_score:
                    # Reopen an older result before creating answer rows; a
                    # graded record rejects new rows until it is reopened.
                    assessment.with_context(eds_replace_legacy_score=True).write({
                        'entry_method': 'import',
                        'state': 'draft',
                        'score': 0.0,
                    })
            else:
                assessment = Assessment.create({
                    'session_id': self.session_id.id,
                    'employee_id': employee_id,
                    'assessment_type': self.assessment_type,
                    'company_id': self.session_id.company_id.id,
                    'entry_method': 'import',
                })
                created_count += 1
            existing_answers = {
                line.question_id.id: line for line in assessment.answer_ids
            }
            if assessment.state == 'distributed' and assessment.entry_method == 'employee':
                # Staff imports that change an open employee form take it over
                # before adding grades. The employee can no longer change the
                # answer after points have been assigned to it.
                changes_open_form = bool(
                    notes[employee_id]
                    and (assessment.notes or '') != next(iter(notes[employee_id]))
                ) or any(
                    not existing_answers.get(question_id)
                    or (existing_answers[question_id].answer_text or '') != vals['answer_text']
                    or existing_answers[question_id].awarded_points != vals['awarded_points']
                    or existing_answers[question_id].is_graded != vals['is_graded']
                    or (existing_answers[question_id].comments or '') != vals['comments']
                    for question_id, vals in answer_rows.items()
                )
                if changes_open_form:
                    assessment.action_take_over_manual_entry()
            changed_employee_text = False
            changed = not bool(existing_by_employee.get(employee_id))
            for question_id, vals in answer_rows.items():
                values = {key: vals[key] for key in (
                    'answer_text', 'awarded_points', 'is_graded', 'comments')}
                old = existing_answers.get(question_id)
                if old:
                    changed_employee_text |= (assessment.entry_method == 'employee'
                                              and (old.answer_text or '') != values['answer_text'])
                    if (old.answer_text or '') != values['answer_text'] or (
                            old.awarded_points != values['awarded_points']
                            or old.is_graded != values['is_graded']
                            or (old.comments or '') != values['comments']):
                        old.write(values)
                        changed = True
                else:
                    changed_employee_text |= assessment.entry_method == 'employee'
                    Answer.create({
                        'assessment_id': assessment.id,
                        'question_id': question_id,
                        **values,
                    })
                    changed = True
            changes = {}
            if notes[employee_id] and (assessment.notes or '') != next(iter(notes[employee_id])):
                changes['notes'] = next(iter(notes[employee_id]))
            if assessment.entry_method not in ('employee', 'import') or changed_employee_text:
                changes['entry_method'] = 'import'
            if changes:
                writer = assessment.with_context(
                    eds_replace_legacy_score=True
                ) if assessment.entry_method == 'score_only' and self.replace_legacy_score else assessment
                writer.write(changes)
                changed = True
            if all(values['is_graded'] for values in answer_rows.values()):
                if changed or assessment.state != 'graded':
                    assessment.action_finalize()
                graded_count += 1
            else:
                if assessment.state == 'draft' or (
                        assessment.state == 'distributed'
                        and assessment.entry_method != 'employee'):
                    assessment.write({
                        'state': 'submitted',
                        'submitted_at': fields.Datetime.now(),
                    })
                pending_count += 1
        self.result_log = _(
            'Import complete. Created: %(created)d; updated: %(updated)d; '
            'graded: %(graded)d; awaiting grading: %(pending)d.') % {
                'created': created_count, 'updated': updated_count,
                'graded': graded_count, 'pending': pending_count,
            }
        return {
            'type': 'ir.actions.act_window',
            'name': _('Assessment Import Result'),
            'res_model': self._name,
            'res_id': self.id,
            'view_mode': 'form',
            'target': 'new',
        }
